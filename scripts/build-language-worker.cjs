#!/usr/bin/env node
const fs = require("node:fs/promises");
const path = require("node:path");
const crypto = require("node:crypto");
const esbuild = require("esbuild");
const root = path.resolve(__dirname, "..");
async function build({ check = false } = {}) {
  const settings = { absWorkingDir: root, entryPoints: ["public/iris-language-worker.mjs"], bundle: true, format: "esm", platform: "browser",
    target: "es2022", write: false, metafile: true, legalComments: "inline", charset: "utf8", logLevel: "silent" };
  const probe = await esbuild.build(settings);
  const inputs = Object.keys(probe.metafile.inputs).sort();
  if (inputs.some(file => file.includes("@codemirror/") || file.includes("iris-syntax-style"))) throw new Error("Worker must stay DOM/view independent");
  const hash = crypto.createHash("sha256").update(esbuild.version).update(JSON.stringify({ ...settings, absWorkingDir: "." }));
  // CRLF checkout policy must not change the semantic bundle identity.
  for (const file of inputs) hash.update(file).update((await fs.readFile(path.join(root, file), "utf8")).replace(/\r\n/g, "\n"));
  const stamp = hash.digest("hex");
  const result = await esbuild.build({ ...settings, define: { IRIS_WORKER_BUILD: JSON.stringify(stamp) },
    banner: { js: "// Generated by scripts/build-language-worker.cjs. Do not edit.\n// Iris GPL-3.0-or-later; bundled @lezer/common and @lezer/lr MIT. See THIRD_PARTY_NOTICES.md." } });
  const outputs = [["worker.mjs", result.outputFiles[0].text], ["version.mjs", `// Generated Worker source/dependency identity.\nexport const build = "${stamp}";\n`]];
  const directory = path.join(root, "public/vendor/language-worker");
  if (!check) await fs.mkdir(directory, { recursive: true });
  for (const [file, text] of outputs) {
    const target = path.join(directory, file);
    if (check) {
      if (await fs.readFile(target, "utf8").catch(() => null) !== text) throw new Error(`Generated Worker differs: ${file}. Run npm run build:language-worker.`);
    } else await fs.writeFile(target, text);
  }
}
if (require.main === module) {
  if (process.argv.slice(2).some(arg => arg !== "--check")) { console.error("Usage: build-language-worker.cjs [--check]"); process.exitCode = 1; }
  else build({ check: process.argv.includes("--check") }).catch(error => { console.error(error); process.exitCode = 1; });
}
module.exports = { build };
